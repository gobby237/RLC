// Funzione di fit ROOT: par[0]=VL0, par[1]=omega0, par[2]=delta, par[3]=Voff
double fitFunc(double *x, double *par) {
    double t      = x[0];
    double VL0    = par[0];
    double omega0 = par[1];
    double delta  = par[2];
    double Voff   = par[3];

    double od2 = omega0*omega0 - delta*delta;
    if (od2 <= 0.0) return Voff;   // sotto-smorzato richiede od2 > 0
    double omega_d = TMath::Sqrt(od2);

    return VL0 * TMath::Exp(-delta * t)
               * (TMath::Cos(omega_d * t) - (delta/omega_d) * TMath::Sin(omega_d * t))
           + Voff;
}

