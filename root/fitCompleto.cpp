// ============================================================
//  RLC Oscillazioni Smorzate – Fit multiparametrico V_L(t)
//
//  Legge fisica (tensione ai capi di L):
//    V_L(t) = VL0 * exp(-delta*t) * [ cos(omega_d*t)
//             - (delta/omega_d) * sin(omega_d*t) ] + Voff
//  dove omega_d = sqrt(omega0^2 - delta^2)
//
//  Parametri liberi: VL0, omega0, delta, Voff
//
//  Incertezza su V (distribuzione triangolare):
//    sigma_V = sqrt( (0.03*|V|/sqrt(6))^2 + (0.050/sqrt(6))^2 )
//    dove 0.050 V = 500 mV / 10  (1/10 scala)
// ============================================================

